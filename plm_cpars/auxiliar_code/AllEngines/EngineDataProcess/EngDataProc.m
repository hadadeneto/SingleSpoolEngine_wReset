%Defines Folder name
TMATSDataFileName = 'TMATSData';
%Defines new name for Alt0dT0.m function - for the case where both the old
%TMATS generation and the new one must work together
NewAlt0dT0FuncName = 'Alt0dT0Mtx';
%Engine data path
