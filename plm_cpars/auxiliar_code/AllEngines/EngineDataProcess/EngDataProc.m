%Verifies if a .m file has been automatically generated by TMATS
if isfile([EngDataFold filesep char(Alt0dT0Names(2))])
    %Sets word for opening file and evals expression
    word = ['fid=fopen(''' EngDataFold filesep char(Alt0dT0Names(2)) ''');'];
    eval(word);
    %Copies lines from file
    Alt0dT0Lines = ReadLines(fid);
    %Closes file
    fclose(fid);
    %
    [row,col] = size(Alt0dT0Lines);
    %Searches for the line where the word '=' is present
    for i = 1:row
        %Defines AuxChar as the i-th line of Alt0dT0Lines
        AuxChar = char(Alt0dT0Lines(i));
        %Finds the indexes for the word '['
        Indexes = find(ismember(char(Alt0dT0Lines(i)),'='));
        %Verifies if any indexes have been found
        if ~isempty(Indexes)
            %             IL = i;
            %Gets the index where the character is ']''
            IHChar = Indexes(1);
            %             %Replaces ']' for ' '
            %             AuxChar(ILChar) = ' ';
            if ~isempty(NewAlt0dT0FuncName)
                %Corrects AuxChar
                AuxChar = [AuxChar(1:IHChar) ' ' NewAlt0dT0FuncName];
                %Corrects first line of Alt0dT0Lines
                Alt0dT0Lines(i) = cellstr(AuxChar);
                %Creates file with new name if it differs from original
                %name and copies the content of original function
                if ~strcmp(NewAlt0dT0FuncName,'Alt0dT0')
                    %Deletes previously created file if it already exists
                    if isfile(['LinPars' filesep NewAlt0dT0FuncName '.m'])
                        delete(['LinPars' filesep NewAlt0dT0FuncName '.m']);
                    end
                    %Creates new file
                    fid = fopen(['LinPars' filesep NewAlt0dT0FuncName '.m'],'w');
                    %Write the lines in the new file
                    WriteLines(Alt0dT0Lines,fid);
                    %Closes files
                    fclose(fid);
                end
            end
            break;
        end
    end
    %Searches for the line where the word '[' is present
    for i = 1:row
        %Defines AuxChar as the i-th line of Alt0dT0Lines
        AuxChar = char(Alt0dT0Lines(i));
        %Finds the indexes for the word '['
        Indexes = find(ismember(char(Alt0dT0Lines(i)),'['));
        %Verifies if any indexes have been found
        if ~isempty(Indexes)
            IL = i;
            %Gets the index where the character is ']''
            ILChar = Indexes(1);
%             %Replaces ']' for ' '
%             AuxChar(ILChar) = ' ';
            %Corrects AuxChar
            AuxChar = AuxChar(ILChar:end);
            %Corrects first line of Alt0dT0Lines
            Alt0dT0Lines(i) = cellstr(AuxChar);
            break;
        end            
    end
    %Searches for the line where the word ']' is present
    for i = 1:row
        %Defines AuxChar as the i-th line of Alt0dT0Lines
        AuxChar = char(Alt0dT0Lines(i));
        %Finds the indexes for the word 'function'
        Indexes = find(ismember(char(Alt0dT0Lines(i)),']'));
        %Verifies if any indexes have been found
        if ~isempty(Indexes)
            IH = i;
            %Corrects AuxChar for excluding the word 'function'
            IHChar = Indexes(1);
%             %Replaces ']' for ','
%             AuxChar(IHChar) = ',';
            %Corrects AuxChar
            AuxChar = AuxChar(1:IHChar);
            %Corrects first line of Alt0dT0Lines
            Alt0dT0Lines(i) = cellstr(AuxChar);
            break;
        end
    end
    %Gets the lines of interest in Alt0dT0Lines
    Alt0dT0Lines = Alt0dT0Lines(IL:IH);   
    %Corrects Alt0dT0 lines for correct direct call of Alt0dT0.m
    [Alt0dT0Lines,Alt0dT0Vars] = Alt0dT0OutNames(Alt0dT0Lines,NewAlt0dT0FuncName);
    %Deletes previously created file if it already exists
    if isfile(['LinPars' filesep 'DirAlt0dT0Call.m'])
        delete(['LinPars' filesep 'DirAlt0dT0Call.m']);
    end
    %Creates file for calling the new generated function directly
    fid = fopen(['LinPars' filesep 'DirAlt0dT0Call.m'],'w');
    %Write the lines in the new file
    WriteLines(Alt0dT0Lines,fid);
    %Closes files
    fclose(fid);
    %Indicates that SetLinMtx must be called and not SetLinPars
    CallSetLinPars = 0;
    CallSetLinMtx = 1;
end

