%Initially, indicates that SetLinPars must be called
CallSetLinPars = 1;
CallSetLinMtx = 0;

%Verifies if a .txt file has been automatically generated by TMATS
if isfile([EngDataFold filesep char(Alt0dT0Names(1))])
    %Sets word for opening file and evals expression
    word = ['fid=fopen(''' EngDataFold filesep char(Alt0dT0Names(1)) ''');'];
