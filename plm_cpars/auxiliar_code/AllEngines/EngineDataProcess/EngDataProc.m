%----------------
%READS .bin FILES
%----------------

BinFileList = [{'iDes_FAN.bin'},{'iDes_HPC.bin'},{'iDes_HPT.bin'},...
               {'iDes_LPC.bin'},{'iDes_LPT.bin'},{'iDes_Nozzle_Core.bin'},...
               {'iDes_Nozzle_Fan.bin'},...
               {'iDes_Compressor.bin'},{'iDes_Turbine.bin'},{'iDes_Nozzle.bin'}];

%Sets the gains for maps and calculated nozzle areas
for i = 1:length(BinFileList)
    %
    if(isfile([EngDataFold filesep char(BinFileList(i))]) > 0)
        %
        fid = fopen([EngDataFold filesep char(BinFileList(i))]);
        FileLines = ReadLines(fid);
        %Verifies which component is being read
        IL = find(char(BinFileList(i)) == '_') + 1;
        IH = find(char(BinFileList(i)) == '.') - 1;
        %
        AuxChar = char(BinFileList(i));
        CompName = AuxChar(IL:IH);
        GainsName = [CompName '_Gains'];
        %
        word = [GainsName '=zeros(1,length(FileLines));' ];
        eval(word);
        %
        for j = 1:length(FileLines)
            word = [GainsName '(j)=' 'str2double(char(FileLines(j)));'];
            eval(word);
        end
    end
end

