            Tt5wmMtx,Tt5CwmMtx,Tt5DwmMtx,...
            Tt6wmMtx,Tt6CwmMtx,Tt6DwmMtx] = WindMillMtxLoad(EngFoldName,UpperFolder);
        
        %Calculates hot sub-idle (with combustion) matrices
        [AshMtx,BshMtx,Pt3CshMtx,Pt3DshMtx,Tt4CshMtx,Tt4DshMtx,...
            NcFANshMtx,WfshMtx,Tt4shMtx,Pt3shMtx,RPMshMtx,...
